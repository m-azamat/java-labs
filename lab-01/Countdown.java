public class Countdown {
  public static void main(String[] args) {
    int i = 10;
    while (i >= 1) {
      System.out.println(i);
      i--;
    }
    System.out.println("Lift off!");

    System.out.println(); 

    for (int k = 10; k >= 1; k--) {
      System.out.println(k);
    }
    System.out.println("Lift off!");
  }
}
 